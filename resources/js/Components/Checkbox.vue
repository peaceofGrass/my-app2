<script setup>
import { computed } from 'vue';

const emit = defineEmits(['update:checked']);

const props = defineProps({
    checked: {
        type: [Array, Boolean],
        required: true,
    },
    value: {
        default: null,
    },
});

const proxyChecked = computed({
    get() {
        return props.checked;
    },

    set(val) {
        emit('update:checked', val);
    },
});
</script>

<template>
    <input
        type="checkbox"
        :value="value"
        v-model="proxyChecked"
        class="rounded border-stone-300 text-orange-600 shadow-sm focus:ring-orange-500 dark:border-stone-700 dark:bg-stone-900 dark:focus:ring-orange-600 dark:focus:ring-offset-stone-800"
    />
</template>
